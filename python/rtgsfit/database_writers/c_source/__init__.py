"""Write the preshot as C source: `preshot_sizes.h` and `preshot_data.c`, compiled into librtgsfit.

* `preshot_sizes.h` defines every size as an `enum` constant, so that array dimensions are integer
  constant expressions (issue #97).
* `preshot_data.c` defines every array declared in `c/src/preshot.h`, row-major and flattened.
  Doubles are written with 17 significant digits, which round-trips exactly.

The files are written atomically (to a temporary name, then renamed) so that a concurrent build
never sees half a file, and only if their content changed so that `make` does not rebuild needlessly.
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path
from typing import TYPE_CHECKING

import numpy as np

from rtgsfit import data_dictionary as dd
from rtgsfit.database_writers import DatabaseWriter
from rtgsfit.preshot import Preshot
from rtgsfit.settings import Settings

if TYPE_CHECKING:
    from rtgsfit.results import Results

SIZES_HEADER = "preshot_sizes.h"
DATA_SOURCE = "preshot_data.c"

# Arrays whose dimension may be zero are padded to one element, as declared in preshot.h.
_OPTIONAL_DIMENSIONS = {"N_PASSIVE"}
_VALUES_PER_LINE = 4


def _format_double(value: float) -> str:
    text = f"{value:.17g}"
    if not any(char in text for char in ".eEn"):
        text += ".0"
    return text


def _format_values(values: np.ndarray, dtype: str) -> str:
    if dtype == "int32":
        items = [str(int(value)) for value in values]
    else:
        items = [_format_double(float(value)) for value in values]
    lines = [", ".join(items[i : i + _VALUES_PER_LINE]) for i in range(0, len(items), _VALUES_PER_LINE)]
    return "    " + ",\n    ".join(lines)


def _c_type(dtype: str) -> str:
    return {"float64": "double", "int32": "int32_t"}[dtype]


def sizes_header(preshot: Preshot) -> str:
    sizes = preshot.sizes
    width = max(len(name) for name in dd.SIZE_NAMES)
    lines = [
        "/* Generated by rtgsfit.database_writers.c_source. Do not edit. */",
        "#ifndef RTGSFIT_PRESHOT_SIZES_H",
        "#define RTGSFIT_PRESHOT_SIZES_H",
        "",
        "enum {",
    ]
    for name in dd.SIZE_NAMES:
        lines.append(f"    {name:<{width}} = {sizes[name]:>8d}, /* {dd.SIZE_DESCRIPTIONS[name]} */")
    lines += ["};", "", "#endif /* RTGSFIT_PRESHOT_SIZES_H */", ""]
    return "\n".join(lines)


def data_source(preshot: Preshot) -> str:
    sizes = preshot.symbolic_sizes()
    lines = [
        "/* Generated by rtgsfit.database_writers.c_source. Do not edit. */",
        f"/* {preshot['INFO:SOURCE']} */",
        f"/* content hash {preshot.content_hash()} */",
        '#include "preshot.h"',
        "",
    ]
    for node in dd.C_NODES:
        if node.path[1] == "SIZES":
            continue
        assert node.c_name is not None
        value = np.asarray(preshot[f"{node.path[1]}:{node.path[2]}"])
        c_type = _c_type(node.dtype)
        if not node.shape:
            lines.append(f"const {c_type} {node.c_name} = {_format_values(value.ravel(), node.dtype).strip()};")
            lines.append("")
            continue
        flat = value.ravel()
        if any(sizes[dim] == 0 for dim in node.shape):
            if not set(dim for dim in node.shape if sizes[dim] == 0) <= _OPTIONAL_DIMENSIONS:
                raise ValueError(f"{node.mds_path} has a zero dimension that preshot.h does not pad")
            # preshot.h declares these PRESHOT_AT_LEAST_ONE(n): pad each empty dimension to 1
            flat = np.zeros(int(np.prod([max(sizes[dim], 1) for dim in node.shape])), dtype=node.dtype)
        lines.append(f"const {c_type} {node.c_name}[{len(flat)}] = {{")
        lines.append(_format_values(flat, node.dtype))
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


def _write_if_changed(path: Path, text: str) -> bool:
    if path.is_file() and path.read_text() == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=path.parent, prefix=f".{path.name}.", delete=False) as handle:
        handle.write(text)
    os.replace(handle.name, path)
    return True


def write_c_source(preshot: Preshot, output_dir: str | Path) -> list[Path]:
    """Write `preshot_sizes.h` and `preshot_data.c` into `output_dir`. Returns the paths written."""
    output_dir = Path(output_dir)
    files = {output_dir / SIZES_HEADER: sizes_header(preshot), output_dir / DATA_SOURCE: data_source(preshot)}
    return [path for path, text in files.items() if _write_if_changed(path, text)]


class CSourceWriter(DatabaseWriter):
    """Writes the preshot into `writers/c_source/output_dir` (default `c/preshot`) for `make`."""

    def write_preshot(self, preshot: Preshot, settings: Settings) -> None:
        from rtgsfit.library import c_directory

        section = settings.get("writers", {}).get("c_source", {})
        output_dir = Path(section.get("output_dir") or c_directory() / "preshot")
        written = write_c_source(preshot, output_dir)
        print(f"Wrote the C preshot to {output_dir} ({len(written)} file(s) changed)")

    def write_results(self, results: Results, settings: Settings) -> None:
        raise NotImplementedError("the c_source writer only writes the preshot")
